#!/usr/bin/env node
// Regenerate schema/mitre-atlas.json, the list of published MITRE ATLAS ids
// that `npm run validate` checks mappings against. Offline and deterministic:
// pass a local copy of the ATLAS release file (format 6), e.g.
//
//   gh api -H "Accept: application/vnd.github.raw" \
//     "repos/mitre-atlas/atlas-data/contents/dist/v6/ATLAS-2026.09.yaml?ref=v2026.09" > ATLAS-2026.09.yaml
//   npm run atlas:update -- ATLAS-2026.09.yaml
//
// Never hand-edit the output; regenerate it from a newer release instead.
import { readFileSync, writeFileSync } from 'node:fs';
import { parse } from 'yaml';
import { ATLAS_PATH, sortKeysDeep } from './lib.mjs';

// ATLAS marks techniques it adapted from ATT&CK with an attack-reference. The
// index records those behaviours in mappings.mitre_attack, unless the ATLAS
// version is specific to AI (its name says so), which ATT&CK cannot express.
const AI_SPECIFIC_NAME = /\bAI\b|\bLLM\b|\bagent\b/i;

const input = process.argv[2];
if (!input) {
  console.error('usage: npm run atlas:update -- <path/to/ATLAS-yyyy.mm.yaml>');
  process.exit(2);
}

const atlas = parse(readFileSync(input, 'utf8'), { maxAliasCount: -1 });
const version = atlas.collection?.version;
if (String(atlas['format-version'] ?? '').split('.')[0] !== '6' || !version) {
  console.error(`atlas-ids: ${input} is not an ATLAS format-6 release file (format-version/collection.version missing)`);
  process.exit(1);
}

const names = (group) =>
  Object.fromEntries(Object.entries(atlas[group] ?? {}).map(([id, o]) => [id, o.name]));

const attackAdapted = {};
for (const [id, t] of Object.entries(atlas.techniques)) {
  const ref = t['attack-reference'];
  if (ref && !AI_SPECIFIC_NAME.test(t.name)) attackAdapted[id] = ref.id ?? String(ref);
}

const out = {
  $comment:
    'Generated by scripts/atlas-ids.mjs from the MITRE ATLAS release named below. Do not hand-edit. ' +
    'attack_adapted lists ATLAS techniques adapted from an ATT&CK technique (given as the value); ' +
    'the index records those in mappings.mitre_attack instead.',
  version: String(version),
  source: `https://github.com/mitre-atlas/atlas-data/blob/v${version}/dist/v6/ATLAS-${version}.yaml`,
  license: 'Apache-2.0 (MITRE ATLAS data, Copyright MITRE)',
  ...sortKeysDeep({
    tactics: names('tactics'),
    techniques: names('techniques'),
    attack_adapted: attackAdapted,
    mitigations: names('mitigations'),
    case_studies: names('case-studies'),
  }),
};

writeFileSync(ATLAS_PATH, JSON.stringify(out, null, 2) + '\n');
console.log(
  `atlas-ids: wrote ATLAS ${version} — ${Object.keys(out.techniques).length} techniques ` +
    `(${Object.keys(attackAdapted).length} ATT&CK-adapted), ${Object.keys(out.tactics).length} tactics, ` +
    `${Object.keys(out.mitigations).length} mitigations, ${Object.keys(out.case_studies).length} case studies`
);
